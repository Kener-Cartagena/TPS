-- V3: General ledger (double-entry bookkeeping) of the ledger module.
--
-- Model (ADR 0006, docs/ledger.md):
--   ledger_accounts   an account of the books, with its current balance
--   journal_entries   one financial event (a deposit, a transfer, ...)
--   ledger_postings   the debit and credit lines of a journal entry
--
-- The application enforces every rule below, but so does the database: even SQL run
-- outside TPS cannot create an unbalanced entry, change or delete a posted entry, mix
-- currencies, or overdraw an account that does not allow a negative balance.

-- ---- Generic guard: rows that must never change ---------------------------------
-- Used by every table that holds financial history (also by later migrations).

CREATE FUNCTION tps_reject_modification() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION '% on table % is not allowed: financial records are immutable',
        TG_OP, TG_TABLE_NAME
        USING ERRCODE = 'restrict_violation';
END;
$$;

COMMENT ON FUNCTION tps_reject_modification() IS
    'Trigger function that rejects UPDATE, DELETE or TRUNCATE on immutable tables';

-- ---- Ledger accounts -------------------------------------------------------------

CREATE TABLE ledger_accounts (
    id               UUID          PRIMARY KEY,
    code             VARCHAR(50)   NOT NULL,
    name             VARCHAR(100)  NOT NULL,
    type             VARCHAR(20)   NOT NULL,
    currency         VARCHAR(3)    NOT NULL,
    balance          NUMERIC(19,2) NOT NULL DEFAULT 0,
    allow_negative   BOOLEAN       NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    closed_at        TIMESTAMPTZ,
    version          BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT uq_ledger_accounts_code UNIQUE (code),
    -- Target of the composite foreign key of ledger_postings (same currency).
    CONSTRAINT uq_ledger_accounts_id_currency UNIQUE (id, currency),
    CONSTRAINT ck_ledger_accounts_code_format CHECK (code ~ '^[A-Z0-9-]{3,50}$'),
    CONSTRAINT ck_ledger_accounts_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_ledger_accounts_type
        CHECK (type IN ('ASSET', 'LIABILITY', 'EQUITY', 'REVENUE', 'EXPENSE')),
    CONSTRAINT ck_ledger_accounts_currency CHECK (currency IN ('HNL', 'USD')),
    CONSTRAINT ck_ledger_accounts_status CHECK (status IN ('OPEN', 'CLOSED')),
    -- The last line of defense against overdrafts.
    CONSTRAINT ck_ledger_accounts_non_negative CHECK (allow_negative OR balance >= 0),
    -- Only an empty account can be closed, and a closed account has a closing time.
    CONSTRAINT ck_ledger_accounts_closed
        CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL)
               AND (status = 'OPEN' OR balance = 0))
);

COMMENT ON TABLE ledger_accounts IS 'Accounts of the general ledger, with their current balance';
COMMENT ON COLUMN ledger_accounts.id IS 'UUIDv7 generated by the application (time-ordered)';
COMMENT ON COLUMN ledger_accounts.code IS 'Stable human-readable code, e.g. SETTLEMENT-HNL or CUS-<account number>';
COMMENT ON COLUMN ledger_accounts.balance IS
    'Balance on the normal side of the type: debits increase ASSET/EXPENSE, credits increase LIABILITY/EQUITY/REVENUE. '
    'Updated in the same database transaction as the postings; always equal to their sum (see the verification report)';
COMMENT ON COLUMN ledger_accounts.allow_negative IS 'FALSE for customer accounts: the balance can never go below zero';
COMMENT ON COLUMN ledger_accounts.version IS 'Optimistic locking version (JPA @Version); postings also lock the row with SELECT ... FOR UPDATE';

-- Accounts are closed, never deleted: their postings must always resolve.
CREATE TRIGGER trg_ledger_accounts_no_delete
    BEFORE DELETE ON ledger_accounts
    FOR EACH ROW EXECUTE FUNCTION tps_reject_modification();
CREATE TRIGGER trg_ledger_accounts_no_truncate
    BEFORE TRUNCATE ON ledger_accounts
    FOR EACH STATEMENT EXECUTE FUNCTION tps_reject_modification();

-- ---- Journal entries ---------------------------------------------------------------

CREATE TABLE journal_entries (
    id           UUID         PRIMARY KEY,
    description  VARCHAR(255) NOT NULL,
    reference    VARCHAR(100),
    posted_at    TIMESTAMPTZ  NOT NULL,
    created_by   UUID         REFERENCES users (id),

    CONSTRAINT ck_journal_entries_description_not_blank CHECK (btrim(description) <> ''),
    CONSTRAINT ck_journal_entries_reference_not_blank CHECK (reference IS NULL OR btrim(reference) <> '')
);

COMMENT ON TABLE journal_entries IS 'One financial event, recorded as balanced debit and credit postings. Immutable';
COMMENT ON COLUMN journal_entries.reference IS 'Identifier of the business operation that caused the entry (e.g. a transaction id)';
COMMENT ON COLUMN journal_entries.created_by IS 'User who caused the entry; NULL for the system';

CREATE INDEX ix_journal_entries_reference ON journal_entries (reference) WHERE reference IS NOT NULL;

-- ---- Postings (the lines of a journal entry) --------------------------------------

CREATE TABLE ledger_postings (
    id                UUID          PRIMARY KEY,
    journal_entry_id  UUID          NOT NULL REFERENCES journal_entries (id),
    line_number       INTEGER       NOT NULL,
    ledger_account_id UUID          NOT NULL,
    currency          VARCHAR(3)    NOT NULL,
    direction         VARCHAR(6)    NOT NULL,
    amount            NUMERIC(19,2) NOT NULL,
    balance_after     NUMERIC(19,2) NOT NULL,
    posted_at         TIMESTAMPTZ   NOT NULL,
    -- Order in which postings were applied. For one account it follows the order of
    -- its balance changes, because the account row is locked while a posting is added.
    sequence_number   BIGINT        GENERATED ALWAYS AS IDENTITY,

    -- A posting can only use the currency of its account.
    CONSTRAINT fk_ledger_postings_account_currency FOREIGN KEY (ledger_account_id, currency)
        REFERENCES ledger_accounts (id, currency),
    CONSTRAINT uq_ledger_postings_line UNIQUE (journal_entry_id, line_number),
    CONSTRAINT uq_ledger_postings_sequence UNIQUE (sequence_number),
    CONSTRAINT ck_ledger_postings_line_number CHECK (line_number >= 1),
    CONSTRAINT ck_ledger_postings_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_ledger_postings_amount_positive CHECK (amount > 0)
);

COMMENT ON TABLE ledger_postings IS 'Debit and credit lines of the journal entries. Immutable';
COMMENT ON COLUMN ledger_postings.amount IS 'Always positive; the direction says whether it is a debit or a credit';
COMMENT ON COLUMN ledger_postings.balance_after IS 'Balance of the account right after this posting (running balance, as on a statement)';

-- Account history, newest first.
CREATE INDEX ix_ledger_postings_account_sequence
    ON ledger_postings (ledger_account_id, sequence_number DESC);

-- ---- Immutability of the journal ---------------------------------------------------

CREATE TRIGGER trg_journal_entries_immutable
    BEFORE UPDATE OR DELETE ON journal_entries
    FOR EACH ROW EXECUTE FUNCTION tps_reject_modification();
CREATE TRIGGER trg_journal_entries_no_truncate
    BEFORE TRUNCATE ON journal_entries
    FOR EACH STATEMENT EXECUTE FUNCTION tps_reject_modification();

CREATE TRIGGER trg_ledger_postings_immutable
    BEFORE UPDATE OR DELETE ON ledger_postings
    FOR EACH ROW EXECUTE FUNCTION tps_reject_modification();
CREATE TRIGGER trg_ledger_postings_no_truncate
    BEFORE TRUNCATE ON ledger_postings
    FOR EACH STATEMENT EXECUTE FUNCTION tps_reject_modification();

-- ---- Double entry: every journal entry is balanced ---------------------------------
-- The lines of an entry are inserted one by one, so the check cannot run per row. It is
-- a constraint trigger DEFERRED to COMMIT: by then all lines exist, and if any entry is
-- unbalanced, has fewer than two lines or mixes currencies, the whole transaction fails.

CREATE FUNCTION tps_check_journal_entry_balanced() RETURNS trigger
    LANGUAGE plpgsql AS
$$
DECLARE
    entry_id   UUID;
    lines      INTEGER;
    currencies INTEGER;
    debits     NUMERIC;
    credits    NUMERIC;
BEGIN
    -- IF, not CASE: PL/pgSQL only resolves NEW.<field> in the branch that runs, and each
    -- table has a different column for the entry id.
    IF TG_TABLE_NAME = 'journal_entries' THEN
        entry_id := NEW.id;
    ELSE
        entry_id := NEW.journal_entry_id;
    END IF;

    SELECT count(*),
           count(DISTINCT currency),
           coalesce(sum(amount) FILTER (WHERE direction = 'DEBIT'), 0),
           coalesce(sum(amount) FILTER (WHERE direction = 'CREDIT'), 0)
      INTO lines, currencies, debits, credits
      FROM ledger_postings
     WHERE journal_entry_id = entry_id;

    IF lines < 2 OR currencies <> 1 OR debits <> credits THEN
        RAISE EXCEPTION 'Journal entry % is not balanced: % lines, % currencies, debits %, credits %',
            entry_id, lines, currencies, debits, credits
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END;
$$;

COMMENT ON FUNCTION tps_check_journal_entry_balanced() IS
    'Deferred check: a journal entry has at least two postings, one currency, and debits equal to credits';

-- Fires for entries without any posting...
CREATE CONSTRAINT TRIGGER trg_journal_entries_balanced
    AFTER INSERT ON journal_entries
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION tps_check_journal_entry_balanced();

-- ...and for every posting added to an entry.
CREATE CONSTRAINT TRIGGER trg_ledger_postings_balanced
    AFTER INSERT ON ledger_postings
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION tps_check_journal_entry_balanced();
