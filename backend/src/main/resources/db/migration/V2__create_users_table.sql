-- V2: Users of the Identity and Access module.
--
-- A user is a person who operates TPS (back-office staff), not a customer.
-- Users are never deleted, only disabled, so the audit trail always resolves.

CREATE TABLE users (
    id                    UUID         PRIMARY KEY,
    username              VARCHAR(50)  NOT NULL,
    full_name             VARCHAR(100) NOT NULL,
    password_hash         VARCHAR(255) NOT NULL,
    role                  VARCHAR(20)  NOT NULL,
    status                VARCHAR(20)  NOT NULL,
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMPTZ,
    password_changed_at   TIMESTAMPTZ  NOT NULL,
    created_at            TIMESTAMPTZ  NOT NULL,
    updated_at            TIMESTAMPTZ  NOT NULL,
    version               BIGINT       NOT NULL DEFAULT 0,

    -- The unique constraint also provides the index used by login and listing.
    CONSTRAINT uq_users_username UNIQUE (username),
    -- Stored normalized (lowercase), so "Admin" and "admin" cannot both exist.
    CONSTRAINT ck_users_username_format CHECK (username ~ '^[a-z0-9._-]{3,50}$'),
    CONSTRAINT ck_users_full_name_not_blank CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_users_role CHECK (role IN ('SYSTEM_ADMIN', 'OPERATOR', 'AUDITOR')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT ck_users_failed_login_attempts CHECK (failed_login_attempts >= 0)
);

COMMENT ON TABLE users IS 'People who operate TPS; authenticated with username and password';
COMMENT ON COLUMN users.id IS 'UUIDv7 generated by the application (time-ordered)';
COMMENT ON COLUMN users.password_hash IS 'Hash with algorithm prefix, e.g. {bcrypt}...; never the password';
COMMENT ON COLUMN users.failed_login_attempts IS 'Consecutive failed logins; reset on success or when the account locks';
COMMENT ON COLUMN users.locked_until IS 'Temporary lockout after too many failed logins; NULL when not locked';
COMMENT ON COLUMN users.version IS 'Optimistic locking version (JPA @Version)';
