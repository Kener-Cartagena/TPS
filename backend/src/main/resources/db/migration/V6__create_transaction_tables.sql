-- V6: Transactions of the transaction engine (transactions module).
--
-- A transaction is one financial operation requested through the API (a deposit, a
-- withdrawal; transfers and reversals come in Phase 5). It records what was asked, by
-- whom, with which idempotency key, and how it ended: COMPLETED with its journal entry, or
-- REJECTED with the business rule that refused it. See ADR 0007 and docs/transactions.md.
--
-- Like the ledger, transactions are never deleted, and the database guards what the
-- application already enforces: the identity of a transaction never changes, and a final
-- status is final.

-- ---- Transactions ------------------------------------------------------------------

CREATE TABLE transactions (
    id                      UUID          PRIMARY KEY,
    type                    VARCHAR(20)   NOT NULL,
    status                  VARCHAR(20)   NOT NULL,
    amount                  NUMERIC(19,2) NOT NULL,
    currency                VARCHAR(3)    NOT NULL,
    source_account_id       UUID          REFERENCES accounts (id),
    destination_account_id  UUID          REFERENCES accounts (id),
    description             VARCHAR(200),
    idempotency_key         VARCHAR(64)   NOT NULL,
    request_hash            VARCHAR(64)   NOT NULL,
    journal_entry_id        UUID          REFERENCES journal_entries (id),
    rejection_code          VARCHAR(50),
    rejection_detail        VARCHAR(255),
    created_by              UUID          NOT NULL REFERENCES users (id),
    created_at              TIMESTAMPTZ   NOT NULL,
    updated_at              TIMESTAMPTZ   NOT NULL,
    processed_at            TIMESTAMPTZ,
    version                 BIGINT        NOT NULL DEFAULT 0,

    -- Idempotency: one transaction per key and user. A retry with the same key finds the
    -- transaction of the first request instead of creating a second one.
    CONSTRAINT uq_transactions_idempotency_key UNIQUE (created_by, idempotency_key),
    -- A journal entry belongs to at most one transaction.
    CONSTRAINT uq_transactions_journal_entry UNIQUE (journal_entry_id),
    CONSTRAINT ck_transactions_type CHECK (type IN ('DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT ck_transactions_status CHECK (status IN
        ('CREATED', 'PENDING', 'PROCESSING', 'COMPLETED', 'FAILED', 'REJECTED', 'REVERSED')),
    CONSTRAINT ck_transactions_currency CHECK (currency IN ('HNL', 'USD')),
    CONSTRAINT ck_transactions_amount_positive CHECK (amount > 0),
    -- Which accounts each type uses: a deposit only credits, a withdrawal only debits.
    CONSTRAINT ck_transactions_accounts CHECK (
        (type = 'DEPOSIT' AND source_account_id IS NULL AND destination_account_id IS NOT NULL)
        OR (type = 'WITHDRAWAL' AND source_account_id IS NOT NULL AND destination_account_id IS NULL)),
    CONSTRAINT ck_transactions_description_not_blank
        CHECK (description IS NULL OR btrim(description) <> ''),
    CONSTRAINT ck_transactions_idempotency_key CHECK (idempotency_key ~ '^[A-Za-z0-9._:-]{1,64}$'),
    CONSTRAINT ck_transactions_request_hash CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    -- Money moved (a journal entry exists) exactly when the transaction completed.
    CONSTRAINT ck_transactions_journal_entry
        CHECK ((status IN ('COMPLETED', 'REVERSED')) = (journal_entry_id IS NOT NULL)),
    -- A rejected or failed transaction always says why, and only those do.
    CONSTRAINT ck_transactions_rejection
        CHECK ((status IN ('REJECTED', 'FAILED')) = (rejection_code IS NOT NULL)
               AND (rejection_code IS NULL) = (rejection_detail IS NULL)),
    -- processed_at: when the transaction reached its outcome.
    CONSTRAINT ck_transactions_processed
        CHECK ((status IN ('COMPLETED', 'FAILED', 'REJECTED', 'REVERSED')) = (processed_at IS NOT NULL))
);

COMMENT ON TABLE transactions IS
    'Financial operations requested through the API and their outcome. Never deleted';
COMMENT ON COLUMN transactions.id IS 'UUIDv7 generated by the application; also the reference of its journal entry';
COMMENT ON COLUMN transactions.source_account_id IS 'Account debited (money out); NULL for deposits';
COMMENT ON COLUMN transactions.destination_account_id IS 'Account credited (money in); NULL for withdrawals';
COMMENT ON COLUMN transactions.idempotency_key IS 'Idempotency-Key header of the request, unique per user';
COMMENT ON COLUMN transactions.request_hash IS
    'SHA-256 (hex) of the request: a retry with the same key and a different request is rejected';
COMMENT ON COLUMN transactions.journal_entry_id IS 'Ledger entry that moved the money; only when COMPLETED or REVERSED';
COMMENT ON COLUMN transactions.rejection_code IS 'Error code of the rule that refused it, e.g. INSUFFICIENT_FUNDS';
COMMENT ON COLUMN transactions.version IS 'Optimistic locking version (JPA @Version)';

-- History of an account, newest first: the account can be on either side.
CREATE INDEX ix_transactions_source ON transactions (source_account_id, created_at DESC)
    WHERE source_account_id IS NOT NULL;
CREATE INDEX ix_transactions_destination ON transactions (destination_account_id, created_at DESC)
    WHERE destination_account_id IS NOT NULL;
CREATE INDEX ix_transactions_created_at ON transactions (created_at DESC);

-- Guards every UPDATE: what was requested never changes, and a final status is final
-- (only COMPLETED may still become REVERSED). The allowed transitions are in Java
-- (TransactionStatus); this is the last line of defense for SQL run outside TPS.
CREATE FUNCTION tps_guard_transaction_update() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF NEW.id IS DISTINCT FROM OLD.id
        OR NEW.type IS DISTINCT FROM OLD.type
        OR NEW.amount IS DISTINCT FROM OLD.amount
        OR NEW.currency IS DISTINCT FROM OLD.currency
        OR NEW.source_account_id IS DISTINCT FROM OLD.source_account_id
        OR NEW.destination_account_id IS DISTINCT FROM OLD.destination_account_id
        OR NEW.description IS DISTINCT FROM OLD.description
        OR NEW.idempotency_key IS DISTINCT FROM OLD.idempotency_key
        OR NEW.request_hash IS DISTINCT FROM OLD.request_hash
        OR NEW.created_by IS DISTINCT FROM OLD.created_by
        OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'The request of transaction % cannot change', OLD.id
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.status IN ('FAILED', 'REJECTED', 'REVERSED')
        OR (OLD.status = 'COMPLETED' AND NEW.status <> 'REVERSED') THEN
        RAISE EXCEPTION 'Transaction % is % and cannot change', OLD.id, OLD.status
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION tps_guard_transaction_update() IS
    'Rejects changes to the request of a transaction and to a final status';

CREATE TRIGGER trg_transactions_guard_update
    BEFORE UPDATE ON transactions
    FOR EACH ROW EXECUTE FUNCTION tps_guard_transaction_update();
CREATE TRIGGER trg_transactions_no_delete
    BEFORE DELETE ON transactions
    FOR EACH ROW EXECUTE FUNCTION tps_reject_modification();
CREATE TRIGGER trg_transactions_no_truncate
    BEFORE TRUNCATE ON transactions
    FOR EACH STATEMENT EXECUTE FUNCTION tps_reject_modification();

-- ---- Status history ----------------------------------------------------------------

CREATE TABLE transaction_status_changes (
    id               UUID        PRIMARY KEY,
    transaction_id   UUID        NOT NULL REFERENCES transactions (id),
    from_status      VARCHAR(20),
    to_status        VARCHAR(20) NOT NULL,
    reason           VARCHAR(50),
    changed_by       UUID        REFERENCES users (id),
    changed_at       TIMESTAMPTZ NOT NULL,
    -- Order of the changes of a transaction; several happen in the same instant.
    sequence_number  BIGINT      GENERATED ALWAYS AS IDENTITY,

    CONSTRAINT uq_transaction_status_changes_sequence UNIQUE (sequence_number),
    CONSTRAINT ck_transaction_status_changes_from CHECK (from_status IS NULL OR from_status IN
        ('CREATED', 'PENDING', 'PROCESSING', 'COMPLETED', 'FAILED', 'REJECTED', 'REVERSED')),
    CONSTRAINT ck_transaction_status_changes_to CHECK (to_status IN
        ('CREATED', 'PENDING', 'PROCESSING', 'COMPLETED', 'FAILED', 'REJECTED', 'REVERSED')),
    CONSTRAINT ck_transaction_status_changes_changed CHECK (from_status IS DISTINCT FROM to_status),
    CONSTRAINT ck_transaction_status_changes_reason_not_blank CHECK (reason IS NULL OR btrim(reason) <> '')
);

COMMENT ON TABLE transaction_status_changes IS
    'Every status of every transaction, in order. The first row (from_status NULL) is its creation. Immutable';
COMMENT ON COLUMN transaction_status_changes.reason IS 'Error code of the rule, for REJECTED and FAILED';

CREATE INDEX ix_transaction_status_changes_transaction
    ON transaction_status_changes (transaction_id, sequence_number);

CREATE TRIGGER trg_transaction_status_changes_immutable
    BEFORE UPDATE OR DELETE ON transaction_status_changes
    FOR EACH ROW EXECUTE FUNCTION tps_reject_modification();
CREATE TRIGGER trg_transaction_status_changes_no_truncate
    BEFORE TRUNCATE ON transaction_status_changes
    FOR EACH STATEMENT EXECUTE FUNCTION tps_reject_modification();
